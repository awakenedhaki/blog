/**
 * Figures whose data points are an embedded raster image (matplotlib
 * `rasterized=True`, or an imshow heatmap). The raster keeps its viridis
 * colours, so remapping the vector legend and lines beside it would make the
 * key disagree with the points. Their data colours stay as exported until
 * the owner decides how to treat them (brief: "Figures that can't be
 * remapped"); chrome is still remapped.
 */
export const RASTER_DATA_FIGURES = new Set([
	'iris-correlation.svg',
	'pca-01-geometry.svg',
	'qt-01-subdivision.svg',
	'sc-01-depth-by-class.svg',
	'sc-02-qc-scatter.svg',
	'sc-03-hvg.svg',
	'sc-04-embedding.svg'
]);

/** The data-colour map for one figure, by filename. */
export function dataColorsFor(filename) {
	if (RASTER_DATA_FIGURES.has(filename)) return {};
	return ORDERED_FIGURES[filename] ?? DATA_COLOR_MAP;
}

/**
 * Remove anything executable from an SVG before it is inlined.
 *
 * Figure markup reaches the page through `{@html}` in Figure.svelte, which
 * performs no escaping — that is the point, since the SVG has to become live
 * DOM for the colour remapping to work. The consequence is that an SVG is not
 * an image here; it is markup with the same privileges as the page.
 *
 * The trust model is "the author wrote it", which is weaker than it sounds now
 * that figures can come from a separate content repository (see WRITING.md),
 * be generated by a plotting library, or be lifted from a paper's
 * supplementary material. None of those are hostile, but none are audited
 * either, and the failure mode is script execution on your domain.
 *
 * Verified against a probe SVG: `<script>`, `onload=` and `javascript:` hrefs
 * all survived the previous pipeline untouched.
 *
 * This is a denylist, and denylists are inherently weaker than parsing the
 * document properly. It is chosen deliberately: a real sanitiser (DOMPurify)
 * needs a DOM, which this module does not have at build time, and would be a
 * runtime dependency for a static site. For author-controlled input this is
 * defence in depth, not the only line of defence — which is why the CSP in
 * static/_headers matters as the actual backstop.
 */
function stripActiveContent(markup) {
	return (
		markup
			// <script> blocks, including ones with attributes
			.replace(/<script[\s\S]*?<\/script\s*>/gi, '')
			.replace(/<script[^>]*\/>/gi, '')
			// inline event handlers: onload=, onclick=, onmouseover=, ...
			.replace(/\son[a-z]+\s*=\s*"[^"]*"/gi, '')
			.replace(/\son[a-z]+\s*=\s*'[^']*'/gi, '')
			.replace(/\son[a-z]+\s*=\s*[^\s>]+/gi, '')
			/*
			 * Dangerous URL schemes in href/xlink:href.
			 *
			 * The allowance for `data:image/...` is REQUIRED, not a relaxation.
			 * matplotlib embeds anything raster — `imshow` heatmaps, colorbars,
			 * rasterised scatter layers — as `<image xlink:href="data:image/png
			 * ;base64,...">`. Blocking `data:` wholesale silently blanked those
			 * elements while the surrounding vector axes kept rendering, which
			 * looks like a broken image rather than a security control.
			 *
			 * Still blocked: `javascript:`, `data:text/html`, and
			 * `data:image/svg+xml` — an SVG payload can itself carry script, so
			 * it is not in the same class as a PNG even though both are images.
			 */
			.replace(
				/(xlink:href|href)\s*=\s*"\s*(javascript:|data:(?!image\/(?:png|jpeg|jpg|gif|webp);))[^"]*"/gi,
				'$1="#"'
			)
			.replace(
				/(xlink:href|href)\s*=\s*'\s*(javascript:|data:(?!image\/(?:png|jpeg|jpg|gif|webp);))[^']*'/gi,
				"$1='#'"
			)
			// <foreignObject> can host arbitrary HTML inside an SVG
			.replace(/<foreignObject[\s\S]*?<\/foreignObject\s*>/gi, '')
	);
}

/* Colour-bearing presentation attributes, in the order they appear in output
   from svglite (R) and, occasionally, matplotlib. */
const COLOR_ATTRS = ['fill', 'stroke', 'stop-color', 'flood-color', 'lighting-color'];

/** Expand '#abc' to '#aabbcc' so the six-digit colour map can match it. */
function normaliseHex(markup) {
	return markup.replace(
		/#([0-9a-f])([0-9a-f])([0-9a-f])\b(?![0-9a-f])/gi,
		(_, r, g, b) => `#${r}${r}${g}${g}${b}${b}`
	);
}

/**
 * Move colour PRESENTATION ATTRIBUTES into the inline style attribute.
 *
 * This is the step that makes R figures work at all. `var()` is a CSS value
 * function: it is only valid in a CSS property value, never in an XML
 * presentation attribute. matplotlib happens to write `style="stroke: #000000"`
 * so substitution works by luck; svglite — the ggplot2 device — writes
 * `stroke='#333333'` as an attribute, and rewriting that to
 * `stroke='var(--ink)'` produces an INVALID attribute. The browser discards it
 * and falls back to the initial value, so a ggplot2 figure would render with
 * black text and missing strokes in both themes.
 *
 * Converting `stroke='#333333'` into `style="stroke:#333333"` first means the
 * colour map's output lands somewhere var() is legal, whichever library drew
 * the figure.
 */
function colorAttrsToStyle(markup) {
	// Match a whole start tag and rewrite its attribute list.
	return markup.replace(/<([a-zA-Z][\w:.-]*)([^>]*?)(\/?)>/g, (whole, tag, attrs, selfClose) => {
		if (!/#[0-9a-fA-F]{6}/.test(attrs)) return whole; // nothing to move

		const moved = [];
		let rest = attrs;

		for (const attr of COLOR_ATTRS) {
			// Only move values that are hex colours; leave `fill="none"`,
			// `fill="url(#grad)"` and friends exactly where they are.
			const re = new RegExp(`\\s${attr}\\s*=\\s*["'](#[0-9a-fA-F]{6})["']`, 'i');
			const hit = rest.match(re);
			if (hit) {
				moved.push(`${attr}:${hit[1]}`);
				rest = rest.replace(re, '');
			}
		}

		if (!moved.length) return whole;

		// Merge into an existing style attribute rather than adding a second
		// one, which would be invalid and silently ignored.
		const existing = rest.match(/\sstyle\s*=\s*["']([^"']*)["']/i);
		if (existing) {
			const merged = `${moved.join(';')};${existing[1]}`;
			rest = rest.replace(/\sstyle\s*=\s*["'][^"']*["']/i, ` style="${merged}"`);
		} else {
			rest = `${rest} style="${moved.join(';')}"`;
		}

		return `<${tag}${rest}${selfClose}>`;
	});
}

/** Escape text for use inside a double-quoted attribute. */
function escapeAttr(text) {
	return text.replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;');
}

/**
 * Prepare raw SVG text for responsive, theme-aware inlining. `filename`
 * picks the data-colour map; `extraColors` (Figure's `colors` prop) wins over
 * both maps. `alt` names the figure: it goes on the <svg> itself, with
 * role="img", so a screen reader announces one named image rather than an
 * unnamed one inside a labelled box.
 */
export function prepareSvg(markup, extraColors = {}, filename = '', alt = '') {
	const colorMap = { ...DEFAULT_COLOR_MAP, ...dataColorsFor(filename), ...extraColors };

	// Sanitise FIRST: every later step rewrites attributes, and running those
	// on markup that still contains handlers risks reassembling something the
	// strip would have caught.
	let out = stripActiveContent(markup)
		// drop the XML prologue/doctype — invalid once inlined into HTML
		.replace(/<\?xml[\s\S]*?\?>/, '')
		.replace(/<!DOCTYPE[\s\S]*?>/, '')
		/*
		 * Remove the <style> block matplotlib injects
		 * (`*{stroke-linejoin: round; stroke-linecap: butt}`).
		 *
		 * Inside a standalone .svg file that rule is scoped to the document.
		 * Inlined into HTML it is NOT: a <style> element in the page applies to
		 * the whole page, so a universal selector from one figure silently
		 * restyled every other SVG on the site — the hex logo, the nav icons,
		 * the GitHub corner. Figure.svelte reapplies the same two properties,
		 * scoped to the figure.
		 */
		.replace(/<style[\s\S]*?<\/style\s*>/gi, '')
		// RDF metadata: several hundred bytes per figure, never rendered.
		.replace(/<metadata[\s\S]*?<\/metadata\s*>/gi, '');

	// Normalise shorthand hexes, then move colour attributes somewhere var()
	// is actually legal. Order matters: both must run before substitution.
	out = colorAttrsToStyle(normaliseHex(out));

	// Strip fixed width/height from the ROOT svg tag only (the viewBox stays,
	// so CSS `width:100%; height:auto` scales the figure to its container),
	// and name it. Any role or label the exporter wrote is replaced.
	out = out.replace(/<svg([^>]*)>/, (_, attrs) => {
		const cleaned = attrs.replace(/\s(width|height|role|aria-label)="[^"]*"/g, '');
		return `<svg${cleaned} role="img" aria-label="${escapeAttr(alt)}">`;
	});

	// Remap chrome colours to CSS variables (case-insensitive hex match).
	for (const [hex, cssVar] of Object.entries(colorMap)) {
		out = out.replaceAll(new RegExp(hex, 'gi'), cssVar);
	}

	return out;
}
